    public static void EnsureAllTablesExist(DbConnection dbConn, ILogger logger)
    {
        try
        {
            if (dbConn.State != System.Data.ConnectionState.Open)
            {
                dbConn.Open();
            }

            using var cmd = dbConn.CreateCommand();
            cmd.CommandText = SchemaSql;
            cmd.ExecuteNonQuery();
            logger.LogInformation("Database schema synchronization completed: all tables verified/created.");
        }
        catch (Exception ex)
        {
            logger.LogWarning(ex, "Schema synchronization encountered an issue; proceeding with startup.");
        }
    }

